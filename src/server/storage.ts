import "server-only";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { env } from "@/lib/env";

/**
 * Object storage. The local-disk driver suits a single server; for several instances implement this
 * interface for S3/R2/GCS (put/get/delete by key) and select it here.
 */
export interface StorageDriver {
  put(key: string, body: Buffer, contentType: string): Promise<void>;
  get(key: string): Promise<Buffer | null>;
  deletePrefix(prefix: string): Promise<void>;
}

const KEY_PATTERN = /^[a-z0-9-]+(\/[a-z0-9-]+)*\.(webp|jpg|png|mp4|webm)$/;
const PREFIX_PATTERN = /^[a-z0-9-]+(\/[a-z0-9-]+)*$/;

function localDriver(root: string): StorageDriver {
  const resolve = (key: string, pattern = KEY_PATTERN) => {
    // Keys are generated by us, but validate anyway so nothing can escape the upload folder.
    if (!pattern.test(key)) throw new Error("Invalid storage key");
    const full = path.resolve(root, key);
    if (!full.startsWith(path.resolve(root) + path.sep)) throw new Error("Invalid storage key");
    return full;
  };
  return {
    async put(key, body) {
      const file = resolve(key);
      await mkdir(path.dirname(file), { recursive: true });
      await writeFile(file, body);
    },
    async get(key) {
      try {
        return await readFile(resolve(key));
      } catch {
        return null;
      }
    },
    async deletePrefix(prefix) {
      await rm(resolve(prefix, PREFIX_PATTERN), { recursive: true, force: true });
    },
  };
}

let driver: StorageDriver | undefined;
export function storage(): StorageDriver {
  driver ??= localDriver(path.resolve(/*turbopackIgnore: true*/ process.cwd(), env.UPLOAD_DIR));
  return driver;
}

export const mediaKeys = (weddingId: string, mediaId: string) => ({
  prefix: `${weddingId}/${mediaId}`,
  full: `${weddingId}/${mediaId}/full.webp`,
  thumb: `${weddingId}/${mediaId}/thumb.webp`,
});
